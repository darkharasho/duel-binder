// One-off generator: npx tsx scripts/pokedex/species.ts
// Writes src/shared/pokedex/species.ts from PokeAPI's English species names.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const URL =
  'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv'
const SIZE = 1025

function parseLine(line: string): string[] {
  const out: string[] = []
  let cur = ''
  let quoted = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') { cur += '"'; i++ }
      else if (c === '"') quoted = false
      else cur += c
    } else if (c === '"') quoted = true
    else if (c === ',') { out.push(cur); cur = '' }
    else cur += c
  }
  out.push(cur)
  return out
}

async function main(): Promise<void> {
  const res = await fetch(URL)
  if (!res.ok) throw new Error(`fetch failed: ${res.status}`)
  const lines = (await res.text()).split(/\r?\n/).slice(1)
  const names: string[] = new Array(SIZE).fill('')
  for (const line of lines) {
    if (!line) continue
    const [id, lang, name] = parseLine(line)
    const n = Number(id)
    if (lang === '9' && n >= 1 && n <= SIZE) names[n - 1] = name.replace(/\u2019/g, "'")
  }
  const missing = names.findIndex((x) => !x)
  if (missing >= 0) throw new Error(`missing species ${missing + 1}`)
  const body = names.map((n) => `  ${JSON.stringify(n)},`).join('\n')
  const out =
    `// Generated by scripts/pokedex/species.ts from PokeAPI\n` +
    `// (${URL}). Do not edit.\n` +
    `// English species names; index n - 1 is national dex number n.\n` +
    `export const SPECIES: readonly string[] = [\n${body}\n]\n`
  writeFileSync(join(__dirname, '../../src/shared/pokedex/species.ts'), out)
  console.log(`wrote ${SIZE} species`)
}

void main()

/**
 * Builds workers/portal/src/site/washes.ts: the site's colour washes, one per card below, made by the
 * app's own wash engine (src/renderer/src/lib/wash) from each card's art on the portal. The site
 * picks one at random on every page load, as the app does per page.
 *
 *   node --import ./scripts/site/ts-hook.mjs scripts/site/washes.ts
 *
 * Needs ImageMagick (`magick`) to read the images.
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import type { GameId } from '../../src/shared/games/types'
import type { RGB } from '../../src/renderer/src/lib/wash/color'
import { css } from '../../src/renderer/src/lib/wash/color'
import { familiesFromPixels } from '../../src/renderer/src/lib/wash/families'
import { field } from '../../src/renderer/src/lib/wash/field'
import { fit } from '../../src/renderer/src/lib/wash/fit'

const PORTAL = 'https://app.duelbinder.com'
const OUT = 'workers/portal/src/site/washes.ts'

/** Fractions of the small image holding the art; must match ART_BOX in lib/wash/sample.ts. */
const CARD_ART = { x: 0.08, y: 0.1, w: 0.84, h: 0.45 }

const CARDS: { game: GameId; name: string; imageId: number; frameType?: string }[] = [
  { game: 'ygo', name: 'Dark Magician', imageId: 36996508, frameType: 'normal' },
  { game: 'ygo', name: 'Blue-Eyes White Dragon', imageId: 89631139, frameType: 'normal' },
  { game: 'ygo', name: 'Dark Magician Girl', imageId: 38033121, frameType: 'effect' },
  { game: 'ygo', name: 'Black Luster Soldier', imageId: 5405694, frameType: 'ritual' },
  { game: 'pkm', name: 'Charizard ex', imageId: 49556840451670 },
  { game: 'pkm', name: 'Umbreon VMAX', imageId: 995260625615027 },
  { game: 'pkm', name: 'Mew ex', imageId: 121773722391840 },
  { game: 'pkm', name: 'Lugia V', imageId: 232602764113106 },
  { game: 'mtg', name: 'Lightning Bolt', imageId: 275987885373 },
  { game: 'mtg', name: 'Counterspell', imageId: 275128721932 },
  { game: 'mtg', name: 'Shivan Dragon', imageId: 279332584578 },
  { game: 'op', name: 'Monkey.D.Luffy', imageId: 552503209712 },
  { game: 'op', name: 'Portgas.D.Ace', imageId: 553840774705 },
  { game: 'op', name: 'Boa Hancock', imageId: 554606597501 }
]

const dir = mkdtempSync(join(tmpdir(), 'site-washes-'))

async function pixels(game: GameId, imageId: number): Promise<RGB[] | null> {
  // Yu-Gi-Oh! has an all-art crop; the other games read the art box of the small card image.
  const size = game === 'ygo' ? 'cropped' : 'small'
  const res = await fetch(`${PORTAL}/img/${size}/${imageId}`)
  if (!res.ok) return null
  const file = join(dir, String(imageId))
  writeFileSync(file, Buffer.from(await res.arrayBuffer()))
  const [w, h] = execFileSync('magick', ['identify', '-format', '%w %h', `${file}[0]`])
    .toString()
    .split(' ')
    .map(Number)
  const box = game === 'ygo' ? { x: 0, y: 0, w: 1, h: 1 } : CARD_ART
  const crop = `${Math.round(box.w * w)}x${Math.round(box.h * h)}+${Math.round(box.x * w)}+${Math.round(box.y * h)}`
  const raw = execFileSync('magick', [
    `${file}[0]`,
    '-crop',
    crop,
    '+repage',
    '-resize',
    '32x32!',
    '-depth',
    '8',
    'rgb:-'
  ])
  const out: RGB[] = []
  for (let i = 0; i + 2 < raw.length; i += 3) out.push([raw[i], raw[i + 1], raw[i + 2]])
  return out
}

const washes: { card: string; base: string; pools: string }[] = []
for (const c of CARDS) {
  const px = await pixels(c.game, c.imageId)
  if (!px) {
    console.warn(`skip ${c.name}: no image on the portal`)
    continue
  }
  const fams = familiesFromPixels(px, c.frameType)
  if (fams.greyArt) {
    console.warn(`skip ${c.name}: grey art`)
    continue
  }
  const fitted = fit(fams, 'dark')
  washes.push({
    card: c.name,
    base: css(fitted.base),
    // Three decimals is plenty for a gradient and halves the size.
    pools: field(fitted, { seed: c.imageId % 2147483647, withBase: false }).replace(
      /(\d+\.\d{3})\d+/g,
      '$1'
    )
  })
  console.log(`${c.name}: ${fams.fams.length} pools, worst contrast ${fitted.worst.toFixed(2)}`)
}

writeFileSync(
  OUT,
  `// Generated by scripts/site/washes.ts; do not edit by hand.
/** Colour washes made from card art by the app's wash engine; the site shows one at random. */
export const WASHES: readonly { card: string; base: string; pools: string }[] = ${JSON.stringify(washes, null, 2)}
`
)
execFileSync('npx', ['prettier', '--write', OUT], { stdio: 'ignore' })
console.log(`wrote ${washes.length} washes to ${OUT}`)
